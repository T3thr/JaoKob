// JaoKob · build the runtime catalog of the journey schemas (ADR-P0-034 D7, ADR-P0-013).
// Usage:  node tools/schema/build-journey-catalog.mjs          write src/data/validation/journey-schema-catalog.js
//         node tools/schema/build-journey-catalog.mjs --check  exit 1 when the committed file is stale
//
// The game cannot fetch schemas at runtime, so the JSON files in specs/schemas/v3.0.0/ are embedded
// in a frozen JavaScript module. The output is deterministic: files sorted by name, two-space JSON.

import { readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const SCHEMA_DIR = new URL('../../specs/schemas/v3.0.0/', import.meta.url);
export const CATALOG_FILE = new URL('../../src/data/validation/journey-schema-catalog.js', import.meta.url);
const PREFIX = 'v3.0.0/';

export async function readJourneySchemas() {
  const names = (await readdir(SCHEMA_DIR)).filter((name) => name.endsWith('.schema.json')).sort();
  const entries = [];
  for (const name of names) entries.push([PREFIX + name, JSON.parse(await readFile(new URL(name, SCHEMA_DIR), 'utf8'))]);
  return entries;
}

export function renderJourneyCatalog(entries) {
  const body = JSON.stringify(Object.fromEntries(entries), null, 2);
  return [
    '/** Generated by tools/schema/build-journey-catalog.mjs from specs/schemas/v3.0.0. Do not edit by hand.',
    ' * Runtime-only local registry: no network or filesystem reads. Trace: ADR-P0-013, ADR-P0-034 D6/D7. */',
    'import { deepFreeze } from "./content-values.js";',
    '',
    `export const JOURNEY_SCHEMA_CATALOG = deepFreeze(${body});`,
    '',
  ].join('\n');
}

async function main() {
  const expected = renderJourneyCatalog(await readJourneySchemas());
  if (process.argv.includes('--check')) {
    let actual = '';
    try { actual = await readFile(CATALOG_FILE, 'utf8'); } catch { actual = ''; }
    if (actual !== expected) {
      console.error('journey-schema-catalog.js ไม่ตรงกับ specs/schemas/v3.0.0 · รัน node tools/schema/build-journey-catalog.mjs');
      process.exit(1);
    }
    console.log('journey-schema-catalog.js ตรงกับ schema ต้นทาง');
    return;
  }
  await writeFile(CATALOG_FILE, expected, 'utf8');
  console.log(`เขียน ${fileURLToPath(CATALOG_FILE)}`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) await main();
